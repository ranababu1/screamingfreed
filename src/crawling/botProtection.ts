/**
 * Detection of bot-protection blocks and challenges (Cloudflare first, plus
 * the other WAFs common in front of WordPress sites).
 *
 * A challenge is not a broken link: the server is alive, it just refused to
 * answer an automated client. Reporting it as "403 broken" (as the auditor
 * used to) floods the report with false positives, so challenged responses
 * get their own `bot_protection` outcome and trigger the fallbacks.
 */

/** Outcome recorded for a link/page that a bot-protection layer blocked. */
export const BOT_PROTECTION_OUTCOME = 'bot_protection';

/** Statuses WAFs use for blocks/challenges. */
const BLOCK_STATUSES: ReadonlySet<number> = new Set([401, 403, 406, 429, 503]);

/** Body markers of known challenge / block pages. */
const BODY_MARKERS: readonly RegExp[] = [
  // Cloudflare managed / JS challenge and Turnstile interstitials
  /<title>\s*Just a moment\.\.\.\s*<\/title>/i,
  /\/cdn-cgi\/challenge-platform\//i,
  /window\._cf_chl_opt/i,
  /cf-browser-verification/i,
  /challenges\.cloudflare\.com/i,
  // Cloudflare WAF block page ("Sorry, you have been blocked")
  /Attention Required! \| Cloudflare/i,
  /cf-error-details/i,
  // Sucuri, Wordfence, Imperva/Incapsula, DataDome, Akamai, AWS WAF
  /Sucuri WebSite Firewall/i,
  /Generated by Wordfence/i,
  /wordfence-blocked/i,
  /Incapsula incident ID/i,
  /_Incapsula_Resource/i,
  /captcha-delivery\.com/i,
  /Reference&#32;&#35;[0-9a-f.]+/i,
  /awswaf/i,
];

/** Lower-cased response headers, as returned by undici. */
type Headers = Record<string, string | string[] | undefined>;

function header(headers: Headers, name: string): string {
  const value = headers[name];
  if (value === undefined) {
    return '';
  }
  return Array.isArray(value) ? value.join(', ') : value;
}

/**
 * True when a response is a bot-protection challenge or block rather than
 * the real resource. `body` may be null (e.g. HEAD) or truncated.
 */
export function isBotChallenge(
  status: number,
  headers: Headers,
  body: string | null,
): boolean {
  // Cloudflare marks every challenge response explicitly.
  if (header(headers, 'cf-mitigated').toLowerCase().includes('challenge')) {
    return true;
  }
  if (!BLOCK_STATUSES.has(status)) {
    return false;
  }
  if (body !== null && BODY_MARKERS.some((pattern) => pattern.test(body))) {
    return true;
  }
  // A HEAD (no body) answered 403/503 by Cloudflare is almost always the
  // edge refusing the client, not the origin reporting a missing page.
  const server = header(headers, 'server').toLowerCase();
  const isCloudflare = server.includes('cloudflare') || header(headers, 'cf-ray') !== '';
  if (body === null && isCloudflare && (status === 403 || status === 503)) {
    return true;
  }
  if (header(headers, 'x-datadome') !== '' || header(headers, 'x-sucuri-block') !== '') {
    return true;
  }
  return false;
}

/** Statuses for which the checker reads the body so a challenge can be recognized. */
export function shouldInspectBody(status: number): boolean {
  return BLOCK_STATUSES.has(status);
}
